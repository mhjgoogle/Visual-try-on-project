// 一轮运行**没拿到产物**的时候，那到底是哪一种没拿到？—— 只有这一处回答。
//
// 两种，别混：
//
//   | 哪一种 | 它是关于谁的 | 后果 |
//   | **失败** | 那一轮 —— 它确实结束了，没结果 | 可以马上重来 |
//   | **问不到** | 我们 —— 等待有上限，超时了我们不知道它怎么样 | **挡住下一轮**，它很可能还在跑 |
//
// 为什么要单独一个模块：codex 复审当场点破，我写的那条「app 的错误路由」守卫
// **自己实现了一遍要验的判断** —— app.js 把 unknown 送错它照样绿。判断散在
// 四个调用点上，就必然有一天有一处忘了改；抽成一处之后，调用点只剩「交给它」。
//
// 依据：ADR-0095 决策 2 / ADR-0064 决策 6。

/** 这个错误是「问不到」，还是「确实失败了」？ */
export function isUnknownOutcome(err) {
  return !!(err && err.category === "unknown");
}
